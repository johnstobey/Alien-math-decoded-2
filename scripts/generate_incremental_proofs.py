#!/usr/bin/env python3
"""Generate and optionally audit extensions that use existing library theorems.

Run from the repository: python3 scripts/generate_incremental_proofs.py --check
Each family has a varying numeric shift or vector dimension, without dummy tags.
The instances specialize existing results; they are not independent discoveries.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "extended_modules"
HEADER = "-- Generated by scripts/generate_incremental_proofs.py; do not edit.\n"
FAMILIES = [
    ("station_add", """(n m : Nat) :
    station ((n + {k}) + m) = station n + station {k} + station m := by
  rw [station_add, station_add]"""),
    ("superstation_add", """(n m : Nat) :
    superstation ((n + {k}) + m) = superstation n + superstation {k} + superstation m := by
  rw [superstation_add, superstation_add]"""),
    ("station_add_closed", """(n m : Nat) :
    ∃ j : Nat, station (n + {k}) + station m = station j := by
  exact station_add_closed (n + {k}) m"""),
    ("superstation_add_closed", """(n m : Nat) :
    ∃ j : Nat, superstation (n + {k}) + superstation m = superstation j := by
  exact superstation_add_closed (n + {k}) m"""),
    ("bridgeTwelve_preserves_addition", """(u v : Fin {dim} → ZMod 2) :
    bridgeTwelve (binaryCoordinate (0 : Fin {dim})) (u + v) =
      bridgeTwelve (binaryCoordinate (0 : Fin {dim})) u +
      bridgeTwelve (binaryCoordinate (0 : Fin {dim})) v := by
  exact bridgeTwelve_preserves_addition (binaryCoordinate (0 : Fin {dim})) u v"""),
    ("bridge144_preserves_addition", """(u v : Fin {dim} → ZMod 2) :
    bridge144 (binaryCoordinate (0 : Fin {dim})) (u + v) =
      bridge144 (binaryCoordinate (0 : Fin {dim})) u +
      bridge144 (binaryCoordinate (0 : Fin {dim})) v := by
  exact bridge144_preserves_addition (binaryCoordinate (0 : Fin {dim})) u v"""),
    ("coordinate_bridgeTwelve_range", """(y : ZMod 12) :
    (∃ v : Fin {dim} → ZMod 2,
      bridgeTwelve (binaryCoordinate (0 : Fin {dim})) v = y) ↔ y = 0 ∨ y = 6 := by
  exact coordinate_bridgeTwelve_range (0 : Fin {dim}) y"""),
    ("coordinate_bridge144_range", """(y : ZMod 144) :
    (∃ v : Fin {dim} → ZMod 2,
      bridge144 (binaryCoordinate (0 : Fin {dim})) v = y) ↔ y = 0 ∨ y = 72 := by
  exact coordinate_bridge144_range (0 : Fin {dim}) y"""),
    ("binary_map_not_surjective_twelve", """ :
    ¬ Function.Surjective
      (bridgeTwelve (binaryCoordinate (0 : Fin {dim}))) := by
  exact binary_map_not_surjective_twelve
    (fun v : Fin {dim} → ZMod 2 => binary_vector_double_zero v)
    (bridgeTwelve (binaryCoordinate (0 : Fin {dim})))"""),
    ("binary_map_not_surjective_144", """ :
    ¬ Function.Surjective
      (bridge144 (binaryCoordinate (0 : Fin {dim}))) := by
  exact binary_map_not_surjective_144
    (fun v : Fin {dim} → ZMod 2 => binary_vector_double_zero v)
    (bridge144 (binaryCoordinate (0 : Fin {dim})))"""),
]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_existing_repository_structure():
    # Positive selection excludes .lake, dependencies, and both generated trees.
    tracked = subprocess.check_output(
        ["git", "ls-files", "-z", "--", "*.lean"], cwd=ROOT
    ).decode().split("\0")
    entries, sources = [], {}
    for relative in sorted(filter(None, tracked)):
        path = Path(relative)
        if not (relative == "IndependentDuodenary.lean" or
                path.parts[0] in {"IndependentDuodenary", "examples"}):
            continue
        source = (ROOT / path).read_text(encoding="utf-8")
        sources[relative] = digest(ROOT / path)
        for match in re.finditer(r"^(?:theorem|lemma)\s+(\w+)", source, re.M):
            entries.append({"file": relative, "name": match[1],
                            "line": source.count("\n", 0, match.start()) + 1})
    if not entries:
        raise RuntimeError("No baseline declarations found")
    return {"declarations": entries, "source_sha256": sources}


def write_owned(path, source):
    if path.exists() and not path.read_text(encoding="utf-8").startswith(HEADER):
        raise RuntimeError(f"Refusing to overwrite non-generated file: {path}")
    path.write_text(source, encoding="utf-8")


def check(manifest):
    # The aggregate imports every batch, detecting cross-module name conflicts.
    subprocess.run(["lake", "build", "extended_modules"], cwd=ROOT, check=True)
    audit = ROOT / ".lake" / "IncrementalProofAudit.lean"
    commands = ["""import extended_modules
import Lean.Util.CollectAxioms

set_option maxHeartbeats 2000000

def checkIncrementalBatch (pairs : Array (Lean.Name × Lean.Name)) (batch : Nat) :
    Lean.Elab.Command.CommandElabM Unit := do
  let env ← Lean.getEnv
  for (name, dependency) in pairs do
    let some ci := env.find? name | throwError "Missing theorem: {name}"
    match ci with
    | .thmInfo _ => pure ()
    | _ => throwError "Not a theorem: {name}"
    unless ci.getUsedConstantsAsSet.contains dependency do
      throwError "Missing direct baseline dependency: {name}"
  -- The standard Lean axiom collector shares its visited set across this batch.
  let action : Lean.CollectAxioms.M Unit := do
    for (name, _) in pairs do
      Lean.CollectAxioms.collect name
  let (_, state) := (action.run env).run {}
  for name in state.axioms do
    unless name == ``propext || name == ``Classical.choice || name == ``Quot.sound do
      throwError "Unexpected axiom: {name}"
  Lean.logInfo m!"INCREMENTAL_BATCH_PASSED {batch} {pairs.size}"
"""]
    expected_batches = {}
    for batch, first in enumerate(range(0, len(manifest["instances"]), 100)):
        instances = manifest["instances"][first:first + 100]
        pairs = [f"(``AlienMath.Extended.{item['name']}, "
                 f"``IndependentDuodenary.{item['base_theorem']})" for item in instances]
        commands.append("run_cmd (checkIncrementalBatch #[\n  " + ",\n  ".join(pairs) +
                        f"\n] {batch})")
        expected_batches[batch] = len(instances)
    audit.write_text("\n\n".join(commands) + "\n", encoding="utf-8")
    result = subprocess.run(["lake", "env", "lean", str(audit)], cwd=ROOT,
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    log = ROOT / ".lake" / "incremental-proof-audit.log"
    log.write_text(result.stdout, encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Dependency/axiom audit failed; see {log}")
    entries = re.findall(r"INCREMENTAL_BATCH_PASSED (\d+) (\d+)", result.stdout)
    completed = {int(batch): int(count) for batch, count in entries}
    if len(entries) != len(expected_batches) or completed != expected_batches:
        raise RuntimeError("Incomplete axiom audit")
    manifest.update(lean_checked=True, direct_baseline_dependencies_checked=True,
                    axiom_audit_checked=True, audited_declarations=sum(completed.values()),
                    file_sha256={name: digest(ROOT / name) for name in manifest["files"]})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=10000)
    parser.add_argument("--batch-size", type=int, default=100)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.count < 1 or args.batch_size < 1:
        parser.error("count and batch-size must be positive")
    baseline = load_existing_repository_structure()
    names = {entry["name"] for entry in baseline["declarations"]}
    if not {name for name, _ in FAMILIES} <= names:
        raise RuntimeError("Required baseline theorems are missing")
    OUTPUT.mkdir(exist_ok=True)
    # Count/configuration changes may remove old batches: refuse that implicitly.
    planned = {f"ExtensionBatch_{i:05d}.lean" for i in range(
        (args.count + args.batch_size - 1) // args.batch_size)}
    stale = {p.name for p in OUTPUT.glob("*.lean")} - planned
    if stale:
        raise RuntimeError(f"Existing batches outside requested configuration: {sorted(stale)}")
    manifest_path = OUTPUT / "manifest.json"
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text())
        if previous.get("generator") != "scripts/generate_incremental_proofs.py":
            raise RuntimeError("Existing manifest belongs to another generator")
        previous["lean_checked"] = False
        previous["direct_baseline_dependencies_checked"] = False
        previous["axiom_audit_checked"] = False
        manifest_path.write_text(json.dumps(previous, indent=2) + "\n")
    instances, modules, files = [], [], []
    for batch, first in enumerate(range(0, args.count, args.batch_size)):
        path = OUTPUT / f"ExtensionBatch_{batch:05d}.lean"
        module = f"extended_modules.{path.stem}"
        modules.append(module)
        files.append(str(path.relative_to(ROOT)))
        source = HEADER + "import IndependentDuodenary.BinaryBridge\n\n"
        source += "namespace AlienMath.Extended\n\nopen IndependentDuodenary\n\n"
        for i in range(first, min(first + args.batch_size, args.count)):
            dependency, template = FAMILIES[i % len(FAMILIES)]
            name = f"derived_{i:05d}"
            source += f"theorem {name} " + template.format(k=i + 1, dim=i + 1) + "\n\n"
            instances.append({"name": name, "base_theorem": dependency,
                              "parameter": i + 1, "module": module})
        source += "end AlienMath.Extended\n"
        if re.search(r"\b(sorry|admit|axiom|native_decide)\b", source):
            raise RuntimeError("Forbidden proof construct")
        write_owned(path, source)
    aggregate = ROOT / "extended_modules.lean"
    write_owned(aggregate, HEADER + "\n".join(f"import {m}" for m in modules) + "\n")
    files.append("extended_modules.lean")
    assert len(instances) == args.count
    assert len({item["name"] for item in instances}) == args.count
    manifest = {"generator": "scripts/generate_incremental_proofs.py",
                "generated_theorems": len(instances), "proof_families": len(FAMILIES),
                "baseline_declarations": len(baseline["declarations"]),
                "baseline": baseline, "instances": instances, "files": files,
                "lean_checked": False, "direct_baseline_dependencies_checked": False,
                "axiom_audit_checked": False,
                "scope": "Parameterized specializations of existing results, not independent discoveries."}
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Baseline: {manifest['baseline_declarations']}; generated: {len(instances)}", flush=True)
    if args.check:
        check(manifest)
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
        print(f"PASSED: {len(instances)} declarations, direct baseline dependencies, and axiom audit.")


if __name__ == "__main__":
    main()
